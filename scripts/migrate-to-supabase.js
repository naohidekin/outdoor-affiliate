#!/usr/bin/env node

/**
 * JSON → Supabase 一括データ移行スクリプト
 *
 * 使い方:
 *   node scripts/migrate-to-supabase.js              # 全データ移行
 *   node scripts/migrate-to-supabase.js --dry-run    # 確認のみ
 */

import { createClient } from "@supabase/supabase-js";
import { loadEnv, readJson } from "../src/lib/x-agent-utils.mjs";

loadEnv();

const supabaseUrl = process.env.SUPABASE_URL;
const supabaseKey = process.env.SUPABASE_SERVICE_ROLE_KEY;

if (!supabaseUrl || !supabaseKey) {
  console.error("SUPABASE_URL / SUPABASE_SERVICE_ROLE_KEY が未設定です");
  process.exit(1);
}

const supabase = createClient(supabaseUrl, supabaseKey);
const dryRun = process.argv.includes("--dry-run");

// ─── マッパー ─────────────────────────────────────────

function articleToRow(a) {
  return {
    id: a.id,
    title: a.title || "",
    slug: a.slug || "",
    category_id: a.categoryId || "",
    content: a.content || "",
    excerpt: a.excerpt || "",
    product_ids: a.productIds || [],
    status: a.status || "draft",
    faqs: a.faqs || [],
    meta_description: a.metaDescription || "",
    tags: a.tags || [],
    created_at: a.createdAt || new Date().toISOString(),
    updated_at: a.updatedAt || new Date().toISOString(),
    published_at: a.publishedAt || null,
    auto_generated: a.autoGenerated || false,
    quality_score: a.qualityScore ?? null,
    scheduled_publish_date: a.scheduledPublishDate ?? null,
    generation_meta: a.generationMeta ?? null,
  };
}

function categoryToRow(c) {
  return {
    id: c.id,
    name: c.name || "",
    slug: c.slug || "",
    description: c.description || "",
    sort_order: c.order ?? 0,
  };
}

function productToRow(p) {
  return {
    id: p.id,
    name: p.name || "",
    brand: p.brand || "",
    price: p.price || 0,
    image_url: p.imageUrl || "",
    affiliate_url: p.affiliateUrl || "",
    amazon_url: p.amazonUrl || "",
    category_id: p.categoryId || "",
    specs: p.specs || {},
    description: p.description || "",
    rating: p.rating || 0,
    created_at: p.createdAt || new Date().toISOString(),
    updated_at: p.updatedAt || new Date().toISOString(),
    auto_added: p.autoAdded ?? null,
    added_by: p.addedBy ?? null,
    added_at: p.addedAt ?? null,
    source_api: p.sourceApi ?? null,
  };
}

// ─── アップサート ───────────────────────────────────

async function upsertBatch(table, rows) {
  if (rows.length === 0) return 0;

  // Supabase upsert は一度に1000行まで。分割して実行
  const BATCH_SIZE = 500;
  let total = 0;

  for (let i = 0; i < rows.length; i += BATCH_SIZE) {
    const batch = rows.slice(i, i + BATCH_SIZE);
    const { error } = await supabase
      .from(table)
      .upsert(batch, { onConflict: "id" });

    if (error) {
      console.error(`  [ERROR] ${table} batch ${i}: ${error.message}`);
      throw error;
    }
    total += batch.length;
  }

  return total;
}

// ─── メイン ─────────────────────────────────────────

async function main() {
  console.log(`\n=== JSON → Supabase データ移行 ${dryRun ? "(DRY RUN)" : ""} ===\n`);

  // データ読み込み
  const articles = readJson("articles.json") || [];
  const categories = readJson("categories.json") || [];
  const products = readJson("products.json") || [];

  console.log(`articles.json:   ${articles.length}件`);
  console.log(`categories.json: ${categories.length}件`);
  console.log(`products.json:   ${products.length}件`);

  if (dryRun) {
    console.log("\n[DRY RUN] 書き込みをスキップします");

    // データ検証
    const articleRows = articles.map(articleToRow);
    const categoryRows = categories.map(categoryToRow);
    const productRows = products.map(productToRow);

    // サンプル表示
    console.log("\n--- articles サンプル ---");
    console.log(JSON.stringify(articleRows[0], null, 2));
    console.log("\n--- categories サンプル ---");
    console.log(JSON.stringify(categoryRows[0], null, 2));
    console.log("\n--- products サンプル ---");
    console.log(JSON.stringify(productRows[0], null, 2));
    return;
  }

  // カテゴリ → 商品 → 記事 の順で投入（外部キー的な依存順）
  console.log("\n[1/3] categories...");
  const catRows = categories.map(categoryToRow);
  const catCount = await upsertBatch("categories", catRows);
  console.log(`  ${catCount}件 upsert 完了`);

  console.log("[2/3] products...");
  const prodRows = products.map(productToRow);
  const prodCount = await upsertBatch("products", prodRows);
  console.log(`  ${prodCount}件 upsert 完了`);

  console.log("[3/3] articles...");
  const artRows = articles.map(articleToRow);
  const artCount = await upsertBatch("articles", artRows);
  console.log(`  ${artCount}件 upsert 完了`);

  // 検証: 行数確認
  console.log("\n--- 検証: 行数チェック ---");
  for (const table of ["categories", "products", "articles"]) {
    const { count, error } = await supabase
      .from(table)
      .select("*", { count: "exact", head: true });
    if (error) {
      console.error(`  ${table}: エラー (${error.message})`);
    } else {
      console.log(`  ${table}: ${count}行`);
    }
  }

  console.log("\n=== 移行完了 ===\n");
}

main().catch((err) => {
  console.error("移行エラー:", err.message);
  process.exit(1);
});
