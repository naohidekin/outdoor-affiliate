#!/usr/bin/env node

/**
 * sync-to-supabase.js — ローカルJSON → Supabase 差分同期
 *
 * パイプライン実行後に orchestrator から呼ばれる。
 * ローカルの articles.json / products.json / categories.json を
 * Supabase にアップサートする。
 *
 * 削除検知: 前回同期時のIDリスト（_sync-state.json）と比較し、
 * 「前回同期済みだがSupabaseに存在しない」IDは管理画面で削除されたと判断してスキップ。
 *
 * 使い方:
 *   node scripts/sync-to-supabase.js                  # 全エンティティ同期
 *   node scripts/sync-to-supabase.js --articles-only  # 記事のみ
 *   node scripts/sync-to-supabase.js --dry-run        # 確認のみ
 */

import { createClient } from "@supabase/supabase-js";
import { loadEnv, readJson, writeJson } from "../src/lib/x-agent-utils.mjs";

loadEnv();

const supabaseUrl = process.env.SUPABASE_URL;
const supabaseKey = process.env.SUPABASE_SERVICE_ROLE_KEY;

if (!supabaseUrl || !supabaseKey) {
  console.log("[sync] SUPABASE_URL / SUPABASE_SERVICE_ROLE_KEY 未設定。スキップ。");
  process.exit(0);
}

const supabase = createClient(supabaseUrl, supabaseKey);

const args = process.argv.slice(2);
const dryRun = args.includes("--dry-run");
const articlesOnly = args.includes("--articles-only");

// ─── マッパー ───────────────────────────────────────

function articleToRow(a) {
  return {
    id: a.id,
    title: a.title || "",
    slug: a.slug || "",
    category_id: a.categoryId || "",
    content: a.content || "",
    excerpt: a.excerpt || "",
    product_ids: a.productIds || [],
    status: a.status || "draft",
    faqs: a.faqs || [],
    meta_description: a.metaDescription || "",
    tags: a.tags || [],
    created_at: a.createdAt || new Date().toISOString(),
    updated_at: a.updatedAt || new Date().toISOString(),
    published_at: a.publishedAt || null,
    auto_generated: a.autoGenerated || false,
    quality_score: a.qualityScore ?? null,
    scheduled_publish_date: a.scheduledPublishDate ?? null,
    generation_meta: a.generationMeta ?? null,
    eyecatch: a.eyecatch ?? null,
  };
}

function categoryToRow(c) {
  return {
    id: c.id,
    name: c.name || "",
    slug: c.slug || "",
    description: c.description || "",
    sort_order: c.order ?? 0,
  };
}

function productToRow(p) {
  return {
    id: p.id,
    name: p.name || "",
    brand: p.brand || "",
    price: p.price || 0,
    image_url: p.imageUrl || "",
    affiliate_url: p.affiliateUrl || "",
    amazon_url: p.amazonUrl || "",
    category_id: p.categoryId || "",
    specs: p.specs || {},
    description: p.description || "",
    rating: p.rating || 0,
    created_at: p.createdAt || new Date().toISOString(),
    updated_at: p.updatedAt || new Date().toISOString(),
    auto_added: p.autoAdded ?? null,
    added_by: p.addedBy ?? null,
    added_at: p.addedAt ?? null,
    source_api: p.sourceApi ?? null,
    availability: p.availability ?? null,
  };
}

// ─── 同期ロジック ──────────────────────────────────

async function getSupabaseIds(table) {
  const { data, error } = await supabase.from(table).select("id");
  if (error) throw error;
  return new Set((data || []).map((r) => r.id));
}

async function syncTable(table, localData, toRow, label, syncState) {
  if (localData.length === 0) {
    console.log(`[sync] ${label}: ローカルデータなし。スキップ。`);
    return [];
  }

  const supabaseIds = await getSupabaseIds(table);
  const prevSyncedIds = new Set(syncState[table] || []);

  const rows = localData.map(toRow);
  const toSync = [];
  let adminDeleted = 0;

  for (const row of rows) {
    // 前回同期済みだがSupabaseに存在しない → 管理画面で削除された
    if (prevSyncedIds.has(row.id) && !supabaseIds.has(row.id)) {
      adminDeleted++;
      continue;
    }
    toSync.push(row);
  }

  if (adminDeleted > 0) {
    console.log(`[sync] ${label}: ${adminDeleted}件は管理画面から削除済み → スキップ`);
  }

  if (dryRun) {
    console.log(`[sync] ${label}: ${toSync.length}件同期予定`);
    return toSync.map((r) => r.id);
  }

  if (toSync.length > 0) {
    const BATCH_SIZE = 500;
    for (let i = 0; i < toSync.length; i += BATCH_SIZE) {
      const batch = toSync.slice(i, i + BATCH_SIZE);
      const { error } = await supabase
        .from(table)
        .upsert(batch, { onConflict: "id" });
      if (error) {
        console.error(`[sync] ${label} エラー: ${error.message}`);
        throw error;
      }
    }
  }

  console.log(`[sync] ${label}: ${toSync.length}件同期完了`);
  return toSync.map((r) => r.id);
}

// ─── メイン ─────────────────────────────────────────

async function autoPullFirst() {
  // ステイル防止: sync前にSupabase最新をローカルにpullしておく
  // 環境変数 `SKIP_AUTO_PULL=1` または `--no-pull` で無効化可
  if (process.env.SKIP_AUTO_PULL === "1" || process.argv.includes("--no-pull")) {
    console.log("[sync-to-supabase] auto-pull skipped");
    return;
  }
  if (dryRun) {
    console.log("[sync-to-supabase] DRY RUN: auto-pull skipped");
    return;
  }
  try {
    console.log("[sync-to-supabase] auto-pull (Supabase → local) ...");
    const { spawn } = await import("node:child_process");
    await new Promise((resolve, reject) => {
      const proc = spawn("node", ["scripts/pull-from-supabase.js"], {
        stdio: "inherit",
        env: process.env,
      });
      proc.on("exit", (code) =>
        code === 0 ? resolve() : reject(new Error(`pull exit ${code}`))
      );
      proc.on("error", reject);
    });
  } catch (err) {
    console.warn(`[sync-to-supabase] auto-pull failed (continue): ${err.message}`);
  }
}

async function main() {
  console.log(`[sync-to-supabase] 開始 ${dryRun ? "(DRY RUN)" : ""}`);

  await autoPullFirst();

  // 前回の同期状態を読み込み
  const syncState = readJson("_sync-state.json") || {};
  const newSyncState = { ...syncState };

  const articles = readJson("articles.json") || [];

  if (!articlesOnly) {
    const categories = readJson("categories.json") || [];
    const products = readJson("products.json") || [];

    newSyncState.categories = await syncTable(
      "categories", categories, categoryToRow, "categories", syncState
    );
    newSyncState.products = await syncTable(
      "products", products, productToRow, "products", syncState
    );
  }

  newSyncState.articles = await syncTable(
    "articles", articles, articleToRow, "articles", syncState
  );

  // 同期状態を保存（次回の削除検知に使用）
  if (!dryRun) {
    newSyncState.lastSyncAt = new Date().toISOString();
    writeJson("_sync-state.json", newSyncState);
    console.log("[sync-to-supabase] _sync-state.json 更新完了");
  }

  console.log("[sync-to-supabase] 完了");
}

main().catch((err) => {
  console.error("[sync-to-supabase] エラー:", err.message);
  process.exit(1);
});
