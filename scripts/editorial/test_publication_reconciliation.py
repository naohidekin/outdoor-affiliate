import tempfile
import unittest
from unittest.mock import patch

from ledger import Ledger, JST, canonical, fingerprint
from nonproduct_contract_fixture import fixture
import publication_reconciliation as r

NOW = datetime(2026, 11, 22, 3, 30, tzinfo=JST)


class ReconciliationTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory(); self.addCleanup(self.tmp.cleanup)
        self.root = Path(self.tmp.name) / 'state'
        self.ledger = Ledger(self.root, 'OWNER')
        self.seo = Path(self.tmp.name) / 'seo'; self.seo.mkdir()
        self.marker = self.seo / '.publication.in-flight.json'
        self.marker_raw = (canonical({'schemaVersion': 1, 'token': r.TOKEN,
            'owner': {'host': socket.gethostname(), 'pid': r.PID},
            'createdAt': '2026-11-22T03:16:26+09:00'}) + '\n').encode()
        self.marker.write_bytes(self.marker_raw)
        self.jobs = {}
        self.remote = {'proofs': []}
        for n, (jid, slug) in enumerate(r.TARGETS.items()):
            b = fixture()['bundle']; b['article'].update(id=jid, slug=slug)
            rev = fingerprint(b)
            job = {'id': jid, 'theme': {'slug': slug}, 'stage': 'approved', 'bundle': b,
                'revision': rev, 'approval': {'action': 'approved', 'user_id': 'OWNER', 'revision': rev},
                'publication': None, 'social': None, 'error': {'status': 'unknown'}, 'week': '2026-11-20'}
            with self.ledger._tx() as db:
                self.ledger._put(db, job, 'fixture')
                db.execute('INSERT INTO effects VALUES (?,?,?,?)', (jid, 'publish', 'unknown', canonical({
                    'status': 'unknown', 'reason': 'publication_requires_reconciliation', 'original': n})))
            self.jobs[jid] = self.ledger.get_job(jid)
            # Fixture is independent of the helper's FIELDS mapping: mirror Node articleRow.
            a = b['article']; row = {wire: a.get(local) for local, wire in {
                'id':'id', 'title':'title', 'slug':'slug', 'categoryId':'category_id', 'content':'content',
                'excerpt':'excerpt', 'productIds':'product_ids', 'status':'status', 'faqs':'faqs',
                'metaDescription':'meta_description', 'tags':'tags', 'createdAt':'created_at', 'updatedAt':'updated_at',
                'publishedAt':'published_at', 'autoGenerated':'auto_generated', 'qualityScore':'quality_score',
                'scheduledPublishDate':'scheduled_publish_date', 'generationMeta':'generation_meta', 'eyecatch':'eyecatch'}.items()}
            row.update(tags=[], auto_generated=False, generation_meta=dict(a['generationMeta'],
                editorialRuntime={'revision': rev, 'author': a['author']}))
            publication = None
            if jid == r.POLE:
                row.update(status='published', published_at='2026-11-21T18:16:29Z', updated_at='2026-11-21T18:16:29+00:00')
                publication = {'verified': True, 'url': 'https://camp-gear-lab.com/articles/' + slug,
                    'contentHash': r._sha(a['content'].encode()), 'remoteUpdatedAt': row['updated_at'],
                    'readback': {'verified': True, 'fingerprint': rev, **fixture()['expectedPublicationReadback']}}
            self.remote['proofs'].append({'id': jid, 'revision': rev, 'kind': 'exact_published' if jid == r.POLE else 'exact_draft',
                'xmin': str(100+n), 'remoteRow': row, 'publication': publication, 'observedAt': NOW.isoformat()})
        self.dead = patch.object(r.os, 'kill', side_effect=ProcessLookupError)
        self.kill = self.dead.start(); self.addCleanup(self.dead.stop)
        with self.ledger._tx() as db:
            db.execute('INSERT INTO meta VALUES (?,?)', ('budget-fixture', '{"calls":53}'))
        self.reader = lambda: copy.deepcopy(self.remote)

    def plan(self):
        return r.prepare(self.ledger, self.seo, self.reader, now=NOW)

    def apply(self, plan):
        return r.apply(self.ledger, self.seo, plan, self.reader, owner_grant=r.OWNER_GRANT, now=NOW)

    def test_prepare_check_readonly_apply_adopts_pole_releases_only_known_drafts_and_preserves_history(self):
        before = r._snapshot(self.ledger); plan = self.plan()
        self.assertEqual('ready', r.check(self.ledger, self.seo, plan, self.reader, now=NOW)['status'])
        self.assertEqual(before, r._snapshot(self.ledger)); self.assertEqual(self.marker_raw, self.marker.read_bytes())
        self.assertEqual('reconciled', self.apply(plan)['status'])
        self.assertFalse(self.marker.exists())
        self.assertEqual(self.marker_raw, (self.seo / ('publication-marker-'+r.TOKEN+'.json')).read_bytes())
        receipt = json.loads((self.root/'publication-reconciliations'/(plan['planHash']+'.json')).read_text())
        self.assertEqual(plan, receipt)
        after = r._snapshot(self.ledger)
        for jid in r.TARGETS:
            self.assertEqual(before[jid]['job']['approval'], after[jid]['job']['approval'])
            self.assertEqual(before[jid]['job']['bundle'], after[jid]['job']['bundle'])
            self.assertEqual(before[jid]['job']['revision'], after[jid]['job']['revision'])
            self.assertIsNone(after[jid]['job']['social'])
            if jid == r.POLE:
                self.assertEqual('published', after[jid]['job']['stage']); self.assertEqual('success', after[jid]['effect']['status'])
                self.assertTrue(after[jid]['job']['publication']['verified'])
                self.assertFalse(self.ledger.claim_effect(jid, 'publish'))
            else:
                self.assertEqual('approved', after[jid]['job']['stage']); self.assertEqual('failed', after[jid]['effect']['status'])
        with sqlite3.connect(self.ledger.db_path) as db:
            events = [json.loads(x[0]) for x in db.execute("SELECT data FROM events WHERE kind='publication_reconciliation_original_unknown'")]
            self.assertEqual(3, len(events))
            self.assertEqual({x['original']['effect']['data'] for x in events}, {x['effect']['data'] for x in before.values()})
            self.assertEqual('{"calls":53}', db.execute("SELECT value FROM meta WHERE key='budget-fixture'").fetchone()[0])
            self.assertEqual(0, db.execute('SELECT count(*) FROM requests').fetchone()[0])
        # Idempotent same-plan finalization does not create more history or calls.
        self.assertEqual('reconciled', self.apply(plan)['status'])
        self.assertTrue(self.ledger.claim_effect(next(j for j in r.TARGETS if j != r.POLE), 'publish'))

    def test_wrong_approval_version_or_actor_refused(self):
        for field, value in [('revision','wrong'), ('user_id','OTHER'), ('action','rejected')]:
            with self.subTest(field=field):
                job = copy.deepcopy(self.jobs[r.POLE]); job['approval'][field]=value
                with self.ledger._tx() as db:self.ledger._put(db, job, 'fixture-change')
                with self.assertRaises(ValueError):self.plan()
                with self.ledger._tx() as db:self.ledger._put(db, self.jobs[r.POLE], 'fixture-restore')

    def test_marker_live_owner_wrong_token_host_legacy_and_flocks_refused(self):
        self.kill.side_effect=None
        with self.assertRaisesRegex(ValueError,'still_alive'):self.plan()
        self.kill.side_effect=ProcessLookupError
        for mutate in [lambda m:m.update(token='other'), lambda m:m['owner'].update(host='other-host')]:
            m=json.loads(self.marker_raw); mutate(m); self.marker.write_text(canonical(m))
            with self.assertRaisesRegex(ValueError,'exact_marker'):self.plan()
        self.marker.write_bytes(self.marker_raw)
        legacy=self.seo/'.publication.lock';legacy.write_text('old')
        with self.assertRaisesRegex(ValueError,'legacy_lock'):self.plan()
        legacy.unlink()
        for lockpath in [self.root/'runtime.flock',self.seo/'.publication.flock']:
            with lockpath.open('a') as lock:
                fcntl.flock(lock, fcntl.LOCK_EX|fcntl.LOCK_NB)
                with self.assertRaises(BlockingIOError):self.plan()
        with (self.root/'runtime.flock').open('a') as run, (self.seo/'.publication.flock').open('a') as seo:
            fcntl.flock(run,fcntl.LOCK_EX);fcntl.flock(seo,fcntl.LOCK_EX)
            self.assertIn('planHash',r.prepare(self.ledger,self.seo,self.reader,runtime_lock=run,seo_lock=seo,now=NOW))

    def test_row_proof_binding_and_freshness_refusals(self):
        original=copy.deepcopy(self.remote)
        mutations=[lambda p:p.update(revision='wrong'),lambda p:p.update(kind='exact_draft'),
            lambda p:p.update(observedAt=(NOW-timedelta(minutes=3)).isoformat()),
            lambda p:p.update(observedAt=(NOW+timedelta(seconds=1)).isoformat()),
            lambda p:p.update(xmin=''), lambda p:p['remoteRow'].update(content='changed'),
            lambda p:p['remoteRow']['generation_meta']['editorialRuntime'].update(revision='wrong'),
            lambda p:p['publication'].update(verified=False),
            lambda p:p['publication']['readback'].update(imageProofs=[])]
        for mutate in mutations:
            self.remote=copy.deepcopy(original);mutate(self.remote['proofs'][0])
            with self.subTest(mutate=mutate),self.assertRaises(ValueError):self.plan()
        self.remote=copy.deepcopy(original);self.remote['proofs'][1]['remoteRow']['status']='published'
        with self.assertRaises(ValueError):self.plan()

    def test_callback_clock_is_sampled_after_network_for_prepare_check_and_apply(self):
        later=NOW+timedelta(seconds=15)
        clock=[NOW]
        def reader():
            clock[0]=later
            value=copy.deepcopy(self.remote)
            for p in value['proofs']:p['observedAt']=later.isoformat()
            return value
        with patch.object(r,'_now',side_effect=lambda now:clock[0]):
            plan=r.prepare(self.ledger,self.seo,reader)
            clock[0]=NOW;r.check(self.ledger,self.seo,plan,reader)
            clock[0]=NOW;r.apply(self.ledger,self.seo,plan,reader,owner_grant=r.OWNER_GRANT)

    def test_cas_job_effect_marker_and_remote_xmin_changes(self):
        plan=self.plan();original=copy.deepcopy(self.remote)
        self.remote['proofs'][1]['xmin']='999'
        with self.assertRaisesRegex(ValueError,'remote_snapshot'):self.apply(plan)
        self.remote=original
        with self.ledger._tx() as db:db.execute("UPDATE effects SET data=? WHERE job_id=?", ('{}',r.POLE))
        with self.assertRaisesRegex(ValueError,'cas_conflict'):self.apply(plan)
        self.assertTrue(self.marker.exists())

    def test_transaction_rollback_keeps_unknown_and_marker_and_immutable_receipt(self):
        plan=self.plan();before=r._snapshot(self.ledger)
        with patch.object(Ledger,'record_publication',side_effect=ValueError('reject')):
            with self.assertRaisesRegex(ValueError,'reject'):self.apply(plan)
        self.assertEqual(before,r._snapshot(self.ledger));self.assertEqual(self.marker_raw,self.marker.read_bytes())
        self.assertTrue((self.root/'publication-reconciliations'/(plan['planHash']+'.json')).exists())
        self.apply(plan)

    def test_archive_failure_leaves_fence_after_db_commit_and_same_plan_can_resume(self):
        plan=self.plan();real=r._immutable
        def fail_archive(path,raw):
            if path.parent==self.seo.resolve():raise OSError('archive failed')
            return real(path,raw)
        with patch.object(r,'_immutable',side_effect=fail_archive):
            with self.assertRaises(OSError):self.apply(plan)
        self.assertTrue(self.marker.exists());self.assertEqual('published',self.ledger.get_job(r.POLE)['stage'])
        self.assertEqual('reconciled',self.apply(plan)['status'])

    def test_immutable_history_trigger_and_no_fake_grant(self):
        plan=self.plan()
        with self.assertRaises(ValueError):r.apply(self.ledger,self.seo,plan,self.reader,owner_grant='other',now=NOW)
        self.apply(plan)
        with self.assertRaises(sqlite3.IntegrityError),self.ledger._tx() as db:db.execute('DELETE FROM events')


