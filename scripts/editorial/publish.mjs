/** One JSON stdin -> JSON stdout. No live action on import.
 * node publish.mjs [stage|publish] [--env-file /explicit/documented/.env.local]
 * Input: {action,bundle,revision,expectedDraft?,approval?}. Caller MUST validate
 * approval's ledger authenticity/owner before invoking; this process checks
 * binding and presence, and cannot authenticate an arbitrary stdin assertion.
 * Never upserts products, synchronizes local data or replays an unknown write.
 */
