#!/usr/bin/env node

/**
 * pull-from-supabase.js — Supabase → ローカルJSON 同期（逆方向sync）
 *
 * 管理画面で記事を公開・編集するとSupabaseだけが更新される。
 * 一方CLI生成スクリプトはローカルJSONを読み書きするため、
 * 放置するとローカルとSupabaseが乖離する（→次回sync-to-supabase.jsで
 * ステイルなローカル値が本番を上書きする危険あり）。
 *
 * 本スクリプトはSupabaseの最新状態をローカルJSONに書き戻す。
 * sync-to-supabase.js が冒頭で自動実行する想定。
 *
 * 使い方:
 *   node scripts/pull-from-supabase.js                # 全エンティティ
 *   node scripts/pull-from-supabase.js --dry-run      # 差分のみ表示
 */

import { createClient } from "@supabase/supabase-js";
import fs from "node:fs";
import path from "node:path";
import { loadEnv } from "../src/lib/x-agent-utils.mjs";

loadEnv();

const supabaseUrl = process.env.SUPABASE_URL;
const supabaseKey = process.env.SUPABASE_SERVICE_ROLE_KEY;

if (!supabaseUrl || !supabaseKey) {
  console.log("[pull] SUPABASE_URL / SUPABASE_SERVICE_ROLE_KEY 未設定。スキップ。");
  process.exit(0);
}

const supabase = createClient(supabaseUrl, supabaseKey);
const dryRun = process.argv.includes("--dry-run");
const DATA_DIR = path.join(process.cwd(), "data");

// ─── snake_case → camelCase マッパー ─────────────────

function rowToArticle(row) {
  return {
    id: row.id,
    title: row.title,
    slug: row.slug,
    categoryId: row.category_id,
    content: row.content,
    excerpt: row.excerpt,
    productIds: row.product_ids || [],
    status: row.status,
    faqs: row.faqs || [],
    metaDescription: row.meta_description || "",
    tags: row.tags || [],
    createdAt: row.created_at,
    updatedAt: row.updated_at,
    publishedAt: row.published_at,
    autoGenerated: row.auto_generated || false,
    qualityScore: row.quality_score ?? undefined,
    scheduledPublishDate: row.scheduled_publish_date ?? undefined,
    generationMeta: row.generation_meta ?? undefined,
  };
}

function rowToCategory(row) {
  return {
    id: row.id,
    name: row.name,
    slug: row.slug,
    description: row.description,
    order: row.sort_order,
  };
}

function rowToProduct(row) {
  return {
    id: row.id,
    name: row.name,
    brand: row.brand,
    price: row.price,
    imageUrl: row.image_url,
    affiliateUrl: row.affiliate_url,
    amazonUrl: row.amazon_url,
    categoryId: row.category_id,
    specs: row.specs || {},
    description: row.description,
    rating: row.rating,
    createdAt: row.created_at,
    updatedAt: row.updated_at,
    autoAdded: row.auto_added ?? undefined,
    addedBy: row.added_by ?? undefined,
    addedAt: row.added_at ?? undefined,
    sourceApi: row.source_api ?? undefined,
  };
}

// ─── 取得 ────────────────────────────────────────────

async function fetchAll(table) {
  const { data, error } = await supabase.from(table).select("*");
  if (error) throw error;
  return data || [];
}

// ─── 書き出し ────────────────────────────────────────

function writeJsonAtomic(filename, data) {
  const filepath = path.join(DATA_DIR, filename);
  const tmppath = `${filepath}.tmp`;
  fs.writeFileSync(tmppath, JSON.stringify(data, null, 2));
  fs.renameSync(tmppath, filepath);
}

function readLocal(filename) {
  try {
    return JSON.parse(fs.readFileSync(path.join(DATA_DIR, filename), "utf8"));
  } catch {
    return [];
  }
}

function readSyncState() {
  try {
    return JSON.parse(
      fs.readFileSync(path.join(DATA_DIR, "_sync-state.json"), "utf8")
    );
  } catch {
    return {};
  }
}

/**
 * Supabase版でローカルを上書きしつつ、「まだ一度も同期されていない
 * ローカル新規アイテム」だけは残す。
 *
 * 背景: 週次パイプラインが商品をローカルJSONに追加 → 同期前に異常終了
 * すると、次回のauto-pullがDB状態で全上書きして新規アイテムが消える
 * 事故があった（2026-06-11: insect-repellent-010〜012 等9商品が消失）。
 * _sync-state.json に記録がない && DBにも無い ID は「push待ちの新規」
 * とみなして保持する。DB側で削除された同期済みアイテムは従来どおり消える。
 */
function mergeKeepUnsynced(remote, local, syncedIds) {
  const remoteIds = new Set(remote.map((r) => r.id));
  const synced = new Set(syncedIds || []);
  const pending = local.filter(
    (item) => item && item.id && !remoteIds.has(item.id) && !synced.has(item.id)
  );
  return { merged: [...remote, ...pending], kept: pending.length };
}

// ─── メイン ─────────────────────────────────────────

async function main() {
  console.log(`[pull] 開始 ${dryRun ? "(DRY RUN)" : ""}`);

  const [catsRaw, prodsRaw, artsRaw] = await Promise.all([
    fetchAll("categories"),
    fetchAll("products"),
    fetchAll("articles"),
  ]);

  const remoteCats = catsRaw.map(rowToCategory).sort((a, b) => (a.order ?? 0) - (b.order ?? 0));
  const remoteProds = prodsRaw.map(rowToProduct);
  const remoteArts = artsRaw.map(rowToArticle);

  // ローカル新規（未同期）アイテムは消さずに残す
  const localCats = readLocal("categories.json");
  const localProds = readLocal("products.json");
  const localArts = readLocal("articles.json");
  const syncState = readSyncState();

  const cats = mergeKeepUnsynced(remoteCats, localCats, syncState.categories);
  const prods = mergeKeepUnsynced(remoteProds, localProds, syncState.products);
  const arts = mergeKeepUnsynced(remoteArts, localArts, syncState.articles);
  const categories = cats.merged;
  const products = prods.merged;
  const articles = arts.merged;

  const diff = (cur, next, kept) =>
    `${cur.length} → ${next.length}${kept > 0 ? `（未同期${kept}件保持）` : ""}`;
  console.log(`[pull] categories: ${diff(localCats, categories, cats.kept)}`);
  console.log(`[pull] products:   ${diff(localProds, products, prods.kept)}`);
  console.log(`[pull] articles:   ${diff(localArts, articles, arts.kept)}`);

  if (dryRun) {
    console.log("[pull] DRY RUN: 書き込みなし");
    return;
  }

  writeJsonAtomic("categories.json", categories);
  writeJsonAtomic("products.json", products);
  writeJsonAtomic("articles.json", articles);

  console.log("[pull] ✅ ローカルJSON書き戻し完了");
}

main().catch((err) => {
  console.error("[pull] エラー:", err.message);
  process.exit(1);
});
