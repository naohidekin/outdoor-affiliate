import { Product } from "./types";

// 楽天アフィリエイトは1商品1個につき報酬上限1,000円（料率アップショップを除く）。
// 2026年7月の成果レポートで実測確認: 売上¥82,665のテントでも報酬¥1,000
// （スポーツ・アウトドア4%なら¥3,306のはずが上限で頭打ち）。
// 一方Amazonは上限なしで実効料率3.67%（7月実績: 売上¥187,210→紹介料¥6,864）。
// 損益分岐は「Amazon 3% × 価格 > 楽天上限¥1,000」となる約¥33,000。
// それ以上の高単価商品はAmazon（2024-08-07に1,000円上限を廃止）を主導線にする。
//
// ── 2026-08-23 追試。この閾値を下げる案が出たので実データで検証した ──
//
// 「楽天のEPCがAmazonの3.6倍（¥23.86 vs ¥6.62、期間を30日で揃えて再計算）
// なのだから、1万円以上は楽天を上に出すべき」という提案があった。
// EPCの数字自体は正しいが、**この閾値を下げると収益は下がる**。
//
// 8月の成果明細（合計 報酬¥12,385 / 売上¥562,070）に、上限が効いている
// 実例が2件あった。どちらも報酬がちょうど¥1,000で止まっている:
//   スノーピーク アメニティドームL  売上¥28,706 → 報酬¥1,000（実効3.5%）
//   中古 THE NORTH FACE ジャケット  売上¥25,960 → 報酬¥1,000
// 前者はこのサイトが紹介している商品。¥28,706 でも上限に当たっている。
//
// では楽天のEPCが高いのはなぜか。**紹介した商品が売れているからではない**。
// 同じ明細で、楽天トラベルの宿泊予約が売上¥319,222（全体の57%）を占めていた。
// 読者が楽天に着地したあと、自分で旅行を予約した分である。料率は1%だが
// 単価が大きいので積み上がる。実効報酬率2.08%の主因もこれ。
//
// つまり楽天の価値は「送客した回数」に乗っており、商品単価には乗らない。
// 高単価商品を楽天に寄せても上限で頭打ちになるだけで、EPCは希薄化する。
// **この閾値は下げない。** 楽天を伸ばすなら、リンクの露出（送客口）を
// 増やす方向と、料率アップ商品への追従で対応する。
// 料率アップは実在する: 同月のスポットクーラー1件が10%で報酬¥3,288、
// これだけで月間報酬の27%を占めた（上限¥1,000も適用されていない）。
export const AMAZON_PRIMARY_PRICE = 33000;

export function isAmazonPrimary(product: Product): boolean {
  return !!product.amazonUrl && product.price >= AMAZON_PRIMARY_PRICE;
}
