// ─── Categories ─────────────────────────────────────

export async function getCategories(): Promise<Category[]> {
  const localCats = readLocalJson<Category>("categories.json");
  const sceneCats = localCats.filter((c) => c.type === "scene");

  if (!isSupabaseConfigured()) {
    return localCats.slice().sort((a, b) => a.order - b.order);
  }
  const { data, error } = await getSupabase()
    .from("categories")
    .select("*")
    .order("sort_order", { ascending: true });
  if (error) throw error;
  const supaCats = (data || []).map(toCategory);
  // シーン別カテゴリはローカルJSONから、通常カテゴリはSupabaseから
  return [...sceneCats, ...supaCats].sort((a, b) => a.order - b.order);
}

export async function getCategoryBySlug(
  slug: string
): Promise<Category | undefined> {
  if (!isSupabaseConfigured()) {
    return readLocalJson<Category>("categories.json").find((c) => c.slug === slug);
  }
  const { data, error } = await getSupabase()
    .from("categories")
    .select("*")
    .eq("slug", slug)
    .maybeSingle();
  if (error) throw error;
  return data ? toCategory(data) : undefined;
}

export async function getCategoryById(
  id: string
): Promise<Category | undefined> {
  if (!isSupabaseConfigured()) {
    return readLocalJson<Category>("categories.json").find((c) => c.id === id);
  }
  const { data, error } = await getSupabase()
    .from("categories")
    .select("*")
    .eq("id", id)
    .maybeSingle();
  if (error) throw error;
  return data ? toCategory(data) : undefined;
}

export async function saveCategory(category: Category): Promise<void> {
  const { error } = await getSupabase()
    .from("categories")
    .upsert(fromCategory(category), { onConflict: "id" });
  if (error) throw error;
}

export async function deleteCategory(id: string): Promise<void> {
  const { error } = await getSupabase().from("categories").delete().eq("id", id);
  if (error) throw error;
}

